"""Copy the shared feature code and the exported models into service/.

service/core/features.py is generated from src/traffic_volume/rowlevel.py;
tests/parity/test_service_sync.py fails if the two ever differ.
"""

from __future__ import annotations

import json
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
HEADER = ("# GENERATED by scripts/sync_service.py from src/traffic_volume/rowlevel.py. Do not edit.\n"
          "# Run `python scripts/sync_service.py` after changing the feature code.\n")


def model_files(metadata: dict) -> list[str]:
    """The ONNX files the metadata refers to: the champion and, if there is one, the calendar-only model."""
    return [metadata["file"]] + ([metadata["fallback"]["file"]] if metadata.get("fallback") else [])


def main() -> None:
    source = (ROOT / "src" / "traffic_volume" / "rowlevel.py").read_text(encoding="utf-8")
    (ROOT / "service" / "core" / "features.py").write_text(HEADER + source, encoding="utf-8")
    export, target = ROOT / "artifacts" / "export", ROOT / "service" / "models"
    if not (export / "metadata.json").exists():
        raise SystemExit(f"missing {export / 'metadata.json'}: run the pipeline (or its export stage) first")
    names = model_files(json.loads((export / "metadata.json").read_text(encoding="utf-8")))
    target.mkdir(parents=True, exist_ok=True)
    for stale in target.glob("*.onnx"):
        stale.unlink()
    for name in [*names, "metadata.json"]:
        shutil.copy2(export / name, target / name)
    print("service synced: core/features.py, models/" + ", models/".join([*names, "metadata.json"]))


if __name__ == "__main__":
    main()
